/** All A1 vocabulary items */
export const a1Vocabulary = vocabulary.filter((v) => v.level === "A1");

/** All A2 vocabulary items */
export const a2Vocabulary = vocabulary.filter((v) => v.level === "A2");

/** Get vocabulary items for a specific category */
export function getVocabularyByCategory(category: string): VocabularyItem[] {
  return vocabulary.filter((v) => v.category === category);
}

/** Get vocabulary items for a specific level */
export function getVocabularyByLevel(level: "A1" | "A2"): VocabularyItem[] {
  return vocabulary.filter((v) => v.level === level);
}

/** Get a single item by ID */
export function getVocabularyById(id: string): VocabularyItem | undefined {
  return vocabulary.find((v) => v.id === id);
}
